#include "NwiroGraphAssetTypeActions.h"
#include "NwiroGraphAsset.h"
#include "Misc/MessageDialog.h"

#define LOCTEXT_NAMESPACE "NwiroGraphAssetTypeActions"

FText FNwiroGraphAssetTypeActions::GetName() const
{
	return LOCTEXT("Name", "Nwiro Generation");
}

FColor FNwiroGraphAssetTypeActions::GetTypeColor() const
{
	return FColor(128, 0, 255);
}

UClass* FNwiroGraphAssetTypeActions::GetSupportedClass() const
{
	return UNwiroGraphAsset::StaticClass();
}

uint32 FNwiroGraphAssetTypeActions::GetCategories()
{
	return EAssetTypeCategories::Misc;
}

void FNwiroGraphAssetTypeActions::OpenAssetEditor(
	const TArray<UObject*>& InObjects,
	TSharedPtr<IToolkitHost> EditWithinLevelEditor)
{
	for (UObject* Obj : InObjects)
	{
		if (UNwiroGraphAsset* NwiroAsset = Cast<UNwiroGraphAsset>(Obj))
		{
			FText Message = FText::Format(
				LOCTEXT("AssetInfo",
					"Nwiro Generation\n\n"
					"Project: {0}\n"
					"Version: {1}\n"
					"Nodes: {2}\n"
					"Generated: {3}\n\n"
					"Prompt: {4}\n\n"
					"This graph was generated by Nwiro and cannot be edited directly."),
				FText::FromString(NwiroAsset->ProjectName),
				FText::FromString(NwiroAsset->VersionId),
				FText::AsNumber(NwiroAsset->NodeCount),
				FText::FromString(NwiroAsset->GeneratedAt),
				FText::FromString(NwiroAsset->OriginalPrompt)
			);

			FMessageDialog::Open(EAppMsgType::Ok, Message);
		}
	}
}

#undef LOCTEXT_NAMESPACE
