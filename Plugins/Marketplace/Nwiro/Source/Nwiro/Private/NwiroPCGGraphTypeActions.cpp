#define LOCTEXT_NAMESPACE "NwiroPCGGraphTypeActions"

FText FNwiroPCGGraphTypeActions::GetName() const
{
	return LOCTEXT("Name", "Nwiro PCG Graph");
}

FColor FNwiroPCGGraphTypeActions::GetTypeColor() const
{
	return FColor(128, 0, 255);
}

UClass* FNwiroPCGGraphTypeActions::GetSupportedClass() const
{
	return UNwiroPCGGraph::StaticClass();
}

uint32 FNwiroPCGGraphTypeActions::GetCategories()
{
	return EAssetTypeCategories::Misc;
}

void FNwiroPCGGraphTypeActions::OpenAssetEditor(
	const TArray<UObject*>& InObjects,
	TSharedPtr<IToolkitHost> EditWithinLevelEditor)
{
	for (UObject* Obj : InObjects)
	{
		if (UNwiroPCGGraph* NwiroGraph = Cast<UNwiroPCGGraph>(Obj))
		{
			// Try to find the parent NwiroGraphAsset in the same package for metadata
			FString MetadataInfo;
			UPackage* Package = NwiroGraph->GetOutermost();
			if (Package)
			{
				TArray<UObject*> PackageObjects;
				GetObjectsWithPackage(Package, PackageObjects);
				for (UObject* PkgObj : PackageObjects)
				{
					if (UNwiroGraphAsset* OwnerAsset = Cast<UNwiroGraphAsset>(PkgObj))
					{
						if (OwnerAsset->GetGraph() == NwiroGraph)
						{
							MetadataInfo = FString::Printf(
								TEXT("\n\nProject: %s\nVersion: %s\nNodes: %d\nGenerated: %s\n\nPrompt: %s"),
								*OwnerAsset->ProjectName,
								*OwnerAsset->VersionId,
								OwnerAsset->NodeCount,
								*OwnerAsset->GeneratedAt,
								*OwnerAsset->OriginalPrompt);
							break;
						}
					}
				}
			}

			FText Message = FText::Format(
				LOCTEXT("GraphLocked",
					"Nwiro PCG Graph (Locked){0}\n\n"
					"This graph was generated by Nwiro and cannot be edited directly."),
				FText::FromString(MetadataInfo));

			FMessageDialog::Open(EAppMsgType::Ok, Message);
		}
	}
	// Intentionally do NOT call Super — prevents the PCG Graph Editor from opening.
}

#undef LOCTEXT_NAMESPACE
